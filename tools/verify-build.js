const fs=require('fs');
const path=require('path');
const {spawnSync}=require('child_process');
const root=path.join(__dirname,'..');
const htmlPath=path.join(root,'dist','ROCKET_RUN.html');
const html=fs.readFileSync(htmlPath,'utf8');
const moduleMatch=html.match(/<script type="module">([\s\S]*?)<\/script>/);
if(!moduleMatch) throw new Error('Built module script not found');
const temp=path.join(root,'dist','.verify-module.mjs');
fs.writeFileSync(temp,moduleMatch[1]);
const check=spawnSync(process.execPath,['--check',temp],{encoding:'utf8'});
fs.rmSync(temp,{force:true});
if(check.status!==0) throw new Error('JavaScript syntax check failed:\n'+check.stderr);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const duplicates=[...new Set(ids.filter((id,i)=>ids.indexOf(id)!==i))];
if(duplicates.length) throw new Error('Duplicate HTML IDs: '+duplicates.join(', '));
for(const token of ['id="camBtn"','id="droneBtn"','@capacitor/app','boostBlurPass','uStrength','PRESS BACK AGAIN TO EXIT','#overlay .screen']) if(!html.includes(token)) throw new Error('Missing expected feature marker: '+token);
for(const file of ['assets/icons/rocket-run-icon-512.png','manifest.webmanifest','sw.js']) if(!fs.existsSync(path.join(root,'dist',file))) throw new Error('Missing built asset: '+file);
console.log('Rocket Run build verification passed.');
console.log('JavaScript syntax: OK');
console.log('HTML IDs: '+ids.length+' unique');
console.log('Camera + drone HUD: present');
console.log('Hyperdrive blur pass: present');
console.log('PWA icon/manifest/service worker: present');
if(html.includes('id=\"pauseBtn\"')||html.includes('id=\"soundBtn\"')) throw new Error('Obsolete pause/sound icon remains in the gameplay HUD');
console.log('Gameplay utility HUD: camera and drone only');
const androidPrep=fs.readFileSync(path.join(root,'tools','prepare-android.js'),'utf8');
if(!androidPrep.includes('android:appCategory=\"game\"')) throw new Error('Android game category metadata missing');
console.log('Android game classification hook: present');
